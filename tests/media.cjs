const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ baseURL: process.env.TEST_URL || 'http://localhost:10778' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  let id;
  try {
    const created = await page.request.post('/api/notes', {data:{title:'媒体回归测试', content:''}});
    id = (await created.json()).id;
    const uploaded = await page.request.post(`/api/notes/${id}/assets`, {data:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aM1sAAAAASUVORK5CYII=', 'base64')});
    const asset = (await uploaded.json()).path;
    await page.request.put(`/api/notes/${id}`, {data:{title:'媒体回归测试',content:`![示例](${asset})`}});
    await page.goto('/');
    await page.waitForFunction(() => document.querySelector('#save-state').textContent === '已保存');
    const videoBytes = Buffer.from(await page.evaluate(async () => {
      const canvas = document.createElement('canvas'); canvas.width = 16; canvas.height = 16;
      const stream = canvas.captureStream(10);
      const recorder = new MediaRecorder(stream, {mimeType:'video/webm;codecs=vp8'});
      const chunks = [];
      recorder.ondataavailable = event => chunks.push(event.data);
      const done = new Promise(resolve => { recorder.onstop = resolve; });
      recorder.start();
      for (let frame=0; frame<8; frame++) {
        const ctx = canvas.getContext('2d'); ctx.fillStyle = frame % 2 ? 'white' : 'black'; ctx.fillRect(0,0,16,16);
        await new Promise(resolve => setTimeout(resolve,100));
      }
      recorder.stop(); await done;
      stream.getTracks().forEach(track => track.stop());
      return Array.from(new Uint8Array(await new Blob(chunks).arrayBuffer()));
    }));
    const serveVideo = route => route.fulfill({status:200,contentType:'video/webm',body:videoBytes});
    await page.route('**/fixture.webm', serveVideo);
    await page.locator('.cm-content').click();
    await page.keyboard.press('ControlOrMeta+a');
    await page.getByRole('button', {name:'图片尺寸',exact:true}).click();
    const dialog = page.locator('.media-dialog');
    assert.equal(await dialog.locator('[name=src]').inputValue(), asset);
    await dialog.locator('[name=width]').fill('240');
    await dialog.locator('[name=height]').fill('120');
    await dialog.getByRole('button',{name:'应用',exact:true}).click();
    await page.locator('#preview-tab').click();
    await page.waitForFunction(() => document.querySelector('#preview-panel img')?.naturalWidth === 1);
    assert.deepEqual(await page.locator('#preview-panel img').evaluate(el => [el.clientWidth, el.clientHeight]), [240,120]);
    await page.locator('#save-note').click();
    await page.waitForFunction(() => document.querySelector('#save-state').textContent === '已保存');
    await page.reload();
    await page.waitForFunction(() => document.querySelector('#save-state').textContent === '已保存');
    await page.locator('#preview-tab').click();
    await page.waitForFunction(() => document.querySelector('#preview-panel img')?.naturalWidth === 1);
    assert.deepEqual(await page.locator('#preview-panel img').evaluate(el => [el.clientWidth,el.clientHeight]),[240,120]);
    await page.locator('#edit-tab').click();
    await page.locator('.cm-content').click();
    await page.keyboard.press('ControlOrMeta+a');
    const source = `<img src="${asset}" width="200" height="100" onerror="window.mediaXSS=true">\n\n<video src="/fixture.webm" controls width="280" height="160" poster="${asset}"></video>\n\n<details><summary>详情</summary>折叠内容</details>\n\n<script>window.mediaXSS=true</script><iframe src="/login"></iframe><img src="javascript:alert(1)" style="position: fixed; width: 50%">`;
    await page.keyboard.insertText(source);
    await page.locator('#preview-tab').click();
    const image = page.locator('#preview-panel img').first();
    await page.waitForFunction(() => document.querySelector('#preview-panel img')?.naturalWidth === 1);
    assert.deepEqual(await image.evaluate(el => [el.clientWidth,el.clientHeight]),[200,100]);
    const video = page.locator('#preview-panel video');
    assert.deepEqual(await video.evaluate(el => [el.clientWidth,el.clientHeight,el.controls]),[280,160,true]);
    await page.waitForFunction(() => document.querySelector('#preview-panel video')?.videoWidth === 16);
    await video.evaluate(el => el.play());
    assert.equal(await video.evaluate(el => el.paused),false);
    assert.match(await video.getAttribute('poster'), /\/api\/notes\//);
    assert.equal(await page.locator('#preview-panel script, #preview-panel iframe, #preview-panel [onerror]').count(),0);
    assert.equal(await page.evaluate(() => Boolean(window.mediaXSS)),false);
    assert.equal(await page.locator('#preview-panel img').last().evaluate(el => el.style.position),'');
    await page.screenshot({path:'/tmp/notes-media-preview.png',fullPage:true});
    await page.locator('#save-note').click();
    await page.waitForFunction(() => document.querySelector('#save-state').textContent === '已保存');
    const share = await page.request.post(`/api/notes/${id}/share`, {data:{days:1}});
    const {path} = await share.json();
    const reader = await browser.newPage({baseURL:process.env.TEST_URL || 'http://localhost:10778'});
    await reader.route('**/fixture.webm',serveVideo);
    await reader.goto(path);
    await reader.waitForFunction(() => document.querySelector('.markdown img')?.naturalWidth === 1);
    assert.deepEqual(await reader.locator('.markdown img').first().evaluate(el => [el.clientWidth,el.clientHeight]),[200,100]);
    assert.deepEqual(await reader.locator('video').evaluate(el => [el.clientWidth,el.clientHeight,el.controls]),[280,160,true]);
    await reader.waitForFunction(() => document.querySelector('video')?.videoWidth === 16);
    assert.match(await reader.locator('video').getAttribute('poster'), /^assets\//);
    assert.equal(await reader.locator('script,iframe,[onerror]').count(),0);
    await page.setViewportSize({width:390,height:844});
    await page.locator('#edit-tab').click();
    await page.locator('.cm-content').click();
    await page.keyboard.press('ControlOrMeta+a');
    await page.keyboard.insertText(`<img src="${asset}" style="width: 800px; height: auto">`);
    await page.locator('#preview-tab').click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true);
    await page.locator('#edit-tab').click();
    await page.locator('.cm-content').click();
    await page.keyboard.press('ControlOrMeta+a');
    await page.keyboard.insertText(`<img src="${asset}" style="width: 50%; height: auto">`);
    await page.locator('#preview-tab').click();
    assert.equal(await page.locator('#preview-panel img').evaluate(el => Math.abs(el.getBoundingClientRect().width - (el.parentElement.clientWidth - 40)/2) < 1),true);
    assert.deepEqual(errors,[]);
    console.log('PASS: media size dialog, Markdown-to-HTML conversion, save/reload, pixel/percentage dimensions, video playback/controls/poster, safe HTML, shared HTML assets and mobile constraints');
  } finally {
    if(id) await page.request.delete(`/api/notes/${id}`);
    await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode=1; });
