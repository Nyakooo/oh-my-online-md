const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ baseURL: process.env.TEST_URL || 'http://localhost:10779' });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  try {
    const stamp = Date.now();
    const folder = '测试文件夹-' + stamp;
    const title = '拖拽笔记-' + stamp;
    const response = await page.request.post('/api/notes', { data: { title, content: '## 文件夹联动测试\n\n保留正文' } });
    assert.equal(response.status(), 201);
    const note = await response.json();
    await page.goto('/');
    await page.locator('#loading-panel').waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: '新建文件夹', exact: true }).click();
    await page.locator('#folder-name').fill(folder);
    await page.locator('#folder-confirm').click();
    const group = page.locator('.folder-group').filter({ has: page.getByText(folder, { exact: true }) });
    await group.waitFor();
    const noteEl = page.locator(`[data-note-id="${note.id}"]`);
    await noteEl.dragTo(group.locator('.folder-row'));
    await group.locator(`[data-note-id="${note.id}"]`).waitFor();
    await page.waitForFunction(() => !folderState.busy);
    let saved = await (await page.request.get('/api/notes/' + note.id)).json();
    assert.equal(saved.folder, folder);
    await page.locator('#title').fill(title + ' 尚未保存');
    await noteEl.dragTo(page.locator('#folder-root-drop'));
    await page.locator('#unsaved-dialog[open]').waitFor();
    await page.locator('#cancel-navigation').click();
    assert.equal(await page.locator('#title').inputValue(), title + ' 尚未保存');
    await noteEl.dragTo(page.locator('#folder-root-drop'));
    await page.locator('#discard-changes').click();
    await page.locator(`#note-list > [data-note-id="${note.id}"]`).waitFor();
    await page.waitForFunction(() => !folderState.busy);
    assert.equal(await page.locator('#title').inputValue(), title);
    await noteEl.dragTo(group.locator('.folder-row'));
    await group.locator(`[data-note-id="${note.id}"]`).waitFor();
    await page.waitForFunction(() => !folderState.busy);
    await group.getByRole('button', { name: folder + '设置', exact: true }).click();
    await page.locator('#folder-protect').check();
    await page.locator('#folder-password').fill(' 任意 🔑 ');
    await page.locator('#folder-confirm').click();
    await page.locator('#folder-dialog').waitFor({ state: 'hidden' });
    await group.getByRole('button', { name: folder + '设置', exact: true }).click();
    await page.getByRole('button', { name: '重新锁定文件夹' }).click();
    await page.waitForFunction(() => !folderState.busy);
    assert.equal(await group.locator('.note-item').count(), 0);
    assert.equal(await page.locator('#title').inputValue(), '');
    assert.equal((await page.request.get('/api/notes/' + note.id)).status(), 403);
    await group.getByRole('button', { name: '解锁文件夹 ' + folder, exact: true }).click();
    await page.locator('#folder-password').fill('wrong');
    await page.locator('#folder-confirm').click();
    await page.getByText('密码不正确，请重试', { exact: true }).waitFor();
    await page.locator('#folder-password').fill(' 任意 🔑 ');
    await page.locator('#folder-confirm').click();
    await page.locator('#folder-dialog').waitFor({ state: 'hidden' });
    await group.locator(`[data-note-id="${note.id}"]`).waitFor();
    await group.getByRole('button', { name: folder + '设置', exact: true }).click();
    await page.locator('#folder-name').fill(folder + '-改名');
    await page.locator('#folder-confirm').click();
    await page.locator('#folder-dialog').waitFor({ state: 'hidden' });
    saved = await (await page.request.get('/api/notes/' + note.id)).json();
    assert.equal(saved.folder, folder + '-改名');
    await page.reload();
    await page.locator('#loading-panel').waitFor({ state: 'hidden' });
    await page.locator(`[data-note-id="${note.id}"]`).click();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('#move-note').click();
    await page.locator('#folder-destination').selectOption('');
    await page.locator('#folder-confirm').click();
    await page.waitForFunction(() => !folderState.busy && state.folder === '');
    saved = await (await page.request.get('/api/notes/' + note.id)).json();
    assert.equal(saved.folder, '');
    assert.ok(saved.content.includes('保留正文'));
    assert.deepEqual(errors, []);
    console.log('PASS: create folder, drag in/out, unsaved cancellation/discard, password/lock/unlock, rename preserving password, reload and mobile move');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
