const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ baseURL: process.env.TEST_URL || 'http://localhost:10778' });
  try {
    const writes = [];
    page.on('request', request => { if (request.method() !== 'GET') writes.push(request.url()); });
    const assertLoading = async () => {
      assert.equal(await page.locator('#loading-panel').isVisible(),true);
      for (const id of ['new-note','save-note','share-note']) assert.equal(await page.locator('#'+id).isVisible(),false,id+' must be hidden while loading');
      assert.equal(await page.locator('#note-search').isDisabled(),true);
      assert.equal(await page.locator('#note-list').evaluate(el => el.inert),true);
      await page.keyboard.press('ControlOrMeta+s');
      await page.keyboard.press('ControlOrMeta+k');
      await page.keyboard.press('ControlOrMeta+Shift+p');
      assert.equal(await page.locator('#sidebar').evaluate(el => el.classList.contains('open')),false);
      assert.equal(await page.locator('#share-dialog').evaluate(el => el.open),false);
      assert.equal(writes.length,0);
    };
    let releaseBundle;
    const bundleGate = new Promise(resolve => {releaseBundle=resolve});
    await page.route('**/editor.bundle.js',async route => {await bundleGate;await route.continue()});
    let release;
    const gate = new Promise(resolve => { release = resolve; });
    await page.route('**/api/notes', async route => { await gate; await route.fulfill({ json: [] }); });
    await page.goto('/',{waitUntil:'commit'});
    await page.locator('#loading-panel').waitFor();
    for (const id of ['new-note','save-note','share-note']) assert.equal(await page.locator('#'+id).isVisible(),false,'initial HTML must hide '+id+' before editor JavaScript loads');
    releaseBundle();
    await page.waitForFunction(() => typeof contentEditor !== 'undefined');
    await assertLoading();
    assert.equal(await page.locator('#loading-panel').isVisible(), true);
    assert.equal(await page.locator('#editor-pane').evaluate(el => el.inert), true);
    assert.equal(await page.locator('#save-note').isDisabled(), true);
    for (const id of ['new-note','save-note','share-note']) assert.equal(await page.locator('#'+id).isVisible(),false, id+' must be hidden while loading');
    release();
    await page.locator('#loading-panel').waitFor({ state: 'hidden' });
    assert.equal(await page.locator('#editor-pane').evaluate(el => el.inert), false);
    for (const id of ['new-note','save-note','share-note']) assert.equal(await page.locator('#'+id).isVisible(),true);
    await page.unroute('**/api/notes');
    await page.route('**/api/notes', route => route.fulfill({ status: 503, body: 'Unavailable' }));
    await page.reload();
    await page.locator('#retry-load').waitFor();
    await assertLoading();
    assert.equal(await page.locator('#editor-pane').evaluate(el => el.inert), true);
    await page.unroute('**/api/notes');
    await page.route('**/api/notes', route => route.fulfill({ json: [{ id: 'fixture', title: '慢速笔记', updatedAt: new Date().toISOString() }, {id:'second',title:'切换失败的笔记',updatedAt:new Date().toISOString()}] }));
    let releaseNote;
    const noteGate = new Promise(resolve => { releaseNote = resolve; });
    await page.route('**/api/notes/fixture', async route => { await noteGate; await route.fulfill({ json: { id: 'fixture', title: '慢速笔记', content: '加载完成' } }); });
    await page.evaluate(() => {
      window.loadingTransitions=[];
      new MutationObserver(records => records.forEach(record => window.loadingTransitions.push(record.oldValue))).observe(document.querySelector('.app'),{attributes:true,attributeFilter:['data-loading'],attributeOldValue:true});
    });
    const noteRequest = page.waitForRequest('**/api/notes/fixture');
    await page.locator('#retry-load').click();
    await noteRequest;
    await assertLoading();
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.locator('#mobile-menu').isVisible(),false);
    await page.screenshot({path:'/tmp/notes-loading-mobile.png'});
    await page.setViewportSize({width:1440,height:1000});
    await page.screenshot({path:'/tmp/notes-loading-desktop.png'});
    assert.equal(await page.locator('#loading-panel').isVisible(), true);
    releaseNote();
    await page.locator('#loading-panel').waitFor({ state: 'hidden' });
    assert.equal(await page.locator('#title').inputValue(), '慢速笔记');
    assert.equal(await page.evaluate(() => window.loadingTransitions.includes('false')),false,'loading must stay active between the list and first note');
    for (const id of ['new-note','save-note','share-note']) assert.equal(await page.locator('#'+id).isVisible(),true);
    let releaseSwitch;
    const switchGate = new Promise(resolve => {releaseSwitch=resolve});
    await page.route('**/api/notes/second',async route => {await switchGate;await route.fulfill({status:503,body:'Unavailable'})});
    const switchRequest = page.waitForRequest('**/api/notes/second');
    await page.locator('.note-item').filter({hasText:'切换失败的笔记'}).click();
    await switchRequest;
    assert.equal(await page.locator('#loading-panel').isVisible(), true);
    assert.equal(await page.locator('#new-note').isVisible(), true);
    assert.equal(await page.locator('#sidebar').evaluate(el => el.inert), true);
    assert.equal(await page.locator('#note-list').evaluate(el => getComputedStyle(el).opacity), '1');
    releaseSwitch();
    await page.locator('#loading-panel').waitFor({state:'hidden'});
    assert.equal(await page.locator('#title').inputValue(),'慢速笔记','failed switch must retain the previous note');
    for (const id of ['new-note','save-note','share-note']) assert.equal(await page.locator('#'+id).isVisible(),true);
    assert.equal(await page.locator('#note-list').evaluate(el => el.inert),false);
    await page.locator('.cm-content').click();
    await page.keyboard.press('ControlOrMeta+End');
    const ime = await page.context().newCDPSession(page);
    await ime.send('Input.imeSetComposition', { text: 'zhongwen', selectionStart: 8, selectionEnd: 8 });
    await ime.send('Input.insertText', { text: '中文输入' });
    await ime.detach();
    assert.equal(await page.evaluate(() => contentEditor.getValue()), '加载完成中文输入');
    await page.locator('#preview-tab').click();
    assert.equal(await page.locator('#preview-panel p').textContent(), '加载完成中文输入');
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: '/tmp/notes-mobile.png', fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.locator('#theme-toggle').click();
    await page.locator('#edit-tab').click();
    await page.screenshot({ path: '/tmp/notes-desktop.png', fullPage: true });
    console.log('PASS: no actions before JavaScript or during loading/failure, blocked shortcuts, continuous initial loading, retry/restored actions, failed navigation recovery, Chinese IME, mobile layout');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
