const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ baseURL: process.env.TEST_URL || 'http://localhost:10778' });
  try {
    let release;
    const gate = new Promise(resolve => { release = resolve; });
    await page.route('**/api/notes', async route => { await gate; await route.fulfill({ json: [] }); });
    await page.goto('/');
    assert.equal(await page.locator('#loading-panel').isVisible(), true);
    assert.equal(await page.locator('#editor-pane').evaluate(el => el.inert), true);
    assert.equal(await page.locator('#save-note').isDisabled(), true);
    release();
    await page.locator('#loading-panel').waitFor({ state: 'hidden' });
    assert.equal(await page.locator('#editor-pane').evaluate(el => el.inert), false);
    await page.unroute('**/api/notes');
    await page.route('**/api/notes', route => route.fulfill({ status: 503, body: 'Unavailable' }));
    await page.reload();
    await page.locator('#retry-load').waitFor();
    assert.equal(await page.locator('#editor-pane').evaluate(el => el.inert), true);
    await page.unroute('**/api/notes');
    await page.route('**/api/notes', route => route.fulfill({ json: [{ id: 'fixture', title: '慢速笔记', updatedAt: new Date().toISOString() }] }));
    let releaseNote;
    const noteGate = new Promise(resolve => { releaseNote = resolve; });
    await page.route('**/api/notes/fixture', async route => { await noteGate; await route.fulfill({ json: { id: 'fixture', title: '慢速笔记', content: '加载完成' } }); });
    const noteRequest = page.waitForRequest('**/api/notes/fixture');
    await page.locator('#retry-load').click();
    await noteRequest;
    assert.equal(await page.locator('#loading-panel').isVisible(), true);
    releaseNote();
    await page.locator('#loading-panel').waitFor({ state: 'hidden' });
    assert.equal(await page.locator('#title').inputValue(), '慢速笔记');
    await page.locator('.cm-content').click();
    await page.keyboard.press('ControlOrMeta+End');
    const ime = await page.context().newCDPSession(page);
    await ime.send('Input.imeSetComposition', { text: 'zhongwen', selectionStart: 8, selectionEnd: 8 });
    await ime.send('Input.insertText', { text: '中文输入' });
    await ime.detach();
    assert.equal(await page.evaluate(() => contentEditor.getValue()), '加载完成中文输入');
    await page.locator('#preview-tab').click();
    assert.equal(await page.locator('#preview-panel p').textContent(), '加载完成中文输入');
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: '/tmp/notes-mobile.png', fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.locator('#theme-toggle').click();
    await page.locator('#edit-tab').click();
    await page.screenshot({ path: '/tmp/notes-desktop.png', fullPage: true });
    console.log('PASS: slow startup, blocked editing during loading, failure/retry, slow note fetch, Chinese IME, mobile preview');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
